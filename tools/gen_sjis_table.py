#!/usr/bin/env python3
"""Generate engine/src/sjis_table.h: Shift-JIS (cp932) double-byte codes -> Unicode."""
import os
leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
out = []
for lead in leads:
    for trail in range(0x40, 0x100):
        try:
            ch = bytes([lead, trail]).decode('cp932')
            out.append(ord(ch) if len(ch) == 1 and ord(ch) < 0x10000 else 0)
        except UnicodeDecodeError:
            out.append(0)
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'engine', 'src', 'sjis_table.h')
with open(path, 'w') as f:
    f.write('/* generated by tools/gen_sjis_table.py: cp932 double-byte -> Unicode. index = lead_index * 192 + (trail - 0x40),\n'
            ' * lead_index over 0x81-0x9F then 0xE0-0xFC */\n#pragma once\n#include <stdint.h>\n')
    f.write(f'static const uint16_t SJIS_TABLE[{len(out)}] = {{\n')
    for i in range(0, len(out), 16):
        f.write('    ' + ', '.join(f'0x{v:04x}' for v in out[i:i + 16]) + ',\n')
    f.write('};\n')
print(len(out), 'entries')
